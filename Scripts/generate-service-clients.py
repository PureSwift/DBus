#!/usr/bin/env python3
"""Generate the supported service API surface; run from any working directory.

Signatures follow the upstream interface references linked in each output file.
Complex arrays preserve DBus's typed wire representation.
"""
from pathlib import Path
import re

from service_definitions import generate_services

ROOT = Path(__file__).resolve().parent.parent
TYPES = {
    'y': ('UInt8', 'byte'), 'n': ('Int16', 'int16'), 'q': ('UInt16', 'uint16'),
    's': ('String', 'string'), 'b': ('Bool', 'boolean'),
    'u': ('UInt32', 'uint32'), 'i': ('Int32', 'int32'),
    't': ('UInt64', 'uint64'), 'x': ('Int64', 'int64'),
    'd': ('Double', 'double'), 'o': ('DBusObjectPath', 'objectPath'),
    'h': ('DBusMessageArgument.FileDescriptor', 'fileDescriptor'),
}


def value_type(signature):
    if signature.startswith('a{'):
        return ('DBusMessageArgument.Dictionary', 'dictionary')
    if signature.startswith('a'):
        return ('DBusMessageArgument.Array', 'array')
    if signature.startswith('('):
        return ('DBusMessageArgument.Structure', 'struct')
    return TYPES[signature]


def lower(name):
    if re.fullmatch(r'[A-Z]+s?', name):
        return name.lower()
    value = re.sub(r'^[A-Z]+(?=[A-Z][a-z]|$)', lambda match: match[0].lower(), name)
    value = value[0].lower() + value[1:]
    return f'`{value}`' if value in {'class', 'type', 'protocol', 'default'} else value


def generate(target, name, service, interface, path, methods, properties, source, bus='system', swift_name=None):
    # The Swift type may be nested while the output filename remains stable.
    if swift_name is None and interface.startswith(service + '.'):
        components = interface[len(service) + 1:].split('.')
        swift_name = '.'.join([target] + [re.sub(r'\d+$', '', component) for component in components])
    namespace, _, type_name = (swift_name or name).rpartition('.')
    lines = [f'// Generated by Scripts/generate-service-clients.py. Do not edit manually.',
             f'// Interface reference: {source}', 'import DBus', '',
             f'/// Client for `{interface}` on the {bus} bus.',
             '/// The caller owns the connection; service errors propagate as DBusError.',
             f'public struct {type_name}: DBusServiceClient {{',
             '    public let proxy: DBusServiceProxy', '']
    default = f' = "{path}"' if path else ''
    lines += [f'    public init(connection: DBusConnection, path: String{default}) throws {{',
              f'        proxy = try DBusServiceProxy(connection: connection, destination: "{service}",',
              f'                                     path: path, interface: "{interface}")', '    }', '']
    for method, args, result in methods:
        args = [(label, sig) for label, sig in args]
        params = ', '.join(f'{label}: {value_type(sig)[0]}' for label, sig in args)
        encoded = ', '.join(f'.{value_type(sig)[1]}({label})' for label, sig in args)
        results = result if isinstance(result, list) else ([('value', result)] if result else [])
        signature = ''.join(sig for _, sig in results)
        ret = ''
        if len(results) == 1:
            ret = f' -> {value_type(results[0][1])[0]}'
        elif results:
            ret = ' -> (' + ', '.join(f'{label}: {value_type(sig)[0]}' for label, sig in results) + ')'
        if result == 'h':
            lines += ['    /// The caller owns the returned descriptor. Close it to release the inhibitor.']
        lines += [f'    public func {lower(method)}({params}) async throws{ret} {{']
        if any(sig.startswith(('a', '(')) for _, sig in args):
            input_signature = ''.join(sig for _, sig in args)
            lines += [f'        try DBusServiceProxy.validate([{encoded}], signature: "{input_signature}")']
        lines += [f'        let reply = try await proxy.call("{method}", arguments: [{encoded}])',
                  f'        try DBusServiceProxy.validate(reply, signature: "{signature}")']
        for index, (label, sig) in enumerate(results):
            case = value_type(sig)[1]
            binding = 'value' if len(results) == 1 else label
            lines += [f'        guard case .{case}(let {binding}) = reply[{index}] else {{',
                      f'            throw DBusProtocolError.invalidValue("Invalid {method} reply")',
                      '        }']
        if results:
            lines += ['        return ' + ('value' if len(results) == 1 else '(' + ', '.join(label for label, _ in results) + ')')]
        lines += ['    }', '']
    for definition in properties:
        prop, sig = definition[:2]
        typ, case = value_type(sig)
        lines += [f'    public var {lower(prop)}: {typ} {{',
                  '        get async throws {',
                  f'            let value = try await proxy.property("{prop}")',
                  f'            try DBusServiceProxy.validate([value], signature: "{sig}")',
                  f'            guard case .{case}(let decoded) = value else {{',
                  f'                throw DBusProtocolError.invalidValue("Invalid {prop} property")',
                  '            }', '            return decoded', '        }', '    }', '']
        if len(definition) == 3 and definition[2] == 'readwrite':
            lines += [f'    public func set{prop}(_ value: {typ}) async throws {{',
                      f'        try DBusServiceProxy.validate([.{case}(value)], signature: "{sig}")',
                      '        try await proxy.connection.setProperty(destination: proxy.destination, path: proxy.path,',
                      f'                                               interface: proxy.interface, name: "{prop}", value: .{case}(value))',
                      '    }', '']
    lines += ['}', '']
    if namespace:
        header = lines[:4]
        if name == target:
            # Some services expose only child interfaces, such as login1.Manager.
            header += [f'public enum {target} {{}}', '']
        lines = header + [f'extension {namespace} {{'] + [
            '    ' + line if line else '' for line in lines[4:-1]
        ] + ['}', '']
    destination = ROOT / 'Sources' / target / f'{name}.swift'
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text('\n'.join(lines))


def main():
    """Generate Swift sources from the checked-in interface definitions."""
    generate_services(generate)


if __name__ == '__main__':
    main()
